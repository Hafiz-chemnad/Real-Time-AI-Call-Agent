# app/tts/test_brain_tts.py
import asyncio
import wave
import os
import sys

from loguru import logger
logger.remove()
logger.add(sys.stderr, level="TRACE")

from pipecat.frames.frames import (
    TextFrame, 
    AudioRawFrame, 
    EndFrame, 
    LLMFullResponseEndFrame, 
    TTSStoppedFrame
)
from pipecat.processors.frame_processor import FrameProcessor
from pipecat.pipeline.pipeline import Pipeline
from pipecat.pipeline.runner import PipelineRunner
from pipecat.pipeline.task import PipelineTask

from app.brain.orchestrator import process_turn
from app.tts.cartesia_client import get_fallback_tts_service

class AudioSaverProcessor(FrameProcessor):
    def __init__(self, filename="brain_tts_test_output.wav"):
        super().__init__()
        self.filename = filename
        self.audio_data = bytearray()
        self.first_chunk_received = False

    async def process_frame(self, frame, direction):
        await super().process_frame(frame, direction)
        
        if isinstance(frame, AudioRawFrame):
            if not self.first_chunk_received:
                print("\n" + "="*50)
                print("SUCCESS: First raw audio buffer received from brain->TTS chain!")
                print("="*50 + "\n")
                self.first_chunk_received = True
            
            self.audio_data.extend(frame.audio)
            await self.push_frame(frame, direction)
            
        elif isinstance(frame, TTSStoppedFrame):
            print("\nStream complete. Saving audio file...")
            self._save_to_wav()
            await self.push_frame(frame, direction)
            await self.push_frame(EndFrame())
            
        else:
            await self.push_frame(frame, direction)

    def _save_to_wav(self):
        with wave.open(self.filename, 'wb') as wav_file:
            wav_file.setnchannels(1)
            wav_file.setsampwidth(2)
            wav_file.setframerate(8000)
            wav_file.writeframes(self.audio_data)
        print(f"Audio saved successfully to: {os.path.abspath(self.filename)}\n")


async def main():
    # 1. Get a REAL response from the brain
    test_question = "What time are you open on Saturday?"
    print(f"\nSending to brain: '{test_question}'")
    
    result = await process_turn(test_question)
    response_text = result["response"]
    
    print(f"Brain response: '{response_text}'")
    print(f"Intent detected: {result.get('intent')}\n")

    # 2. Build pipeline directly with Cartesia (Confirmed working Tier 1)
    tts_service = get_fallback_tts_service()
    audio_saver = AudioSaverProcessor()

    pipeline = Pipeline([tts_service, audio_saver])
    task = PipelineTask(pipeline)
    runner = PipelineRunner()

    async def inject_brain_response():
        await asyncio.sleep(2)
        print("Sending brain's response into TTS...")
        # Queue the actual response generated by process_turn
        await task.queue_frame(TextFrame(text=response_text))
        await asyncio.sleep(0.1)
        await task.queue_frame(LLMFullResponseEndFrame())

    asyncio.create_task(inject_brain_response())

    print("Starting Brain -> TTS Validation...")
    await runner.run(task)

if __name__ == "__main__":
    asyncio.run(main())
    sys.exit(0)